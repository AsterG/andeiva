// Package dhcpkea compiles bounded DHCP configuration for Kea 2.6.3. It has no
// filesystem, process, network or configuration-store effects.
package dhcpkea

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"net/netip"
	"sort"
	"strconv"
	"strings"

	"github.com/AsterG/andeiva/internal/dhcpserver"
)

const (
	EngineVersion    = "2.6.3"
	LeaseFile        = "/var/lib/andeiva/dhcp-server/leases4.csv"
	MaxArtifactBytes = 1 << 20
)

var ErrInvalid = errors.New("ANDEIVA_DHCP_KEA_INVALID")

// Binding is operational assembly input, not an administrative JSON contract.
// The caller must prove live LAN ownership and persist the scope/SubnetID
// association across revisions/restarts; this package creates no ID allocator.
type Binding struct {
	Interface dhcpserver.Binding `json:"-"`
	Name      string             `json:"-"`
	SubnetID  uint32             `json:"-"`
}

// Digest identifies generated bytes only; it is not a configuration revision,
// authorization, service observation or proof of lease-database continuity.
// Disabled configuration produces the zero Artifact, with no service document.
type Artifact struct {
	Enabled bool
	JSON    []byte
	Digest  string
}

func Compile(config dhcpserver.Config, bindings []Binding) (Artifact, error) {
	if len(bindings) != len(config.Scopes) || len(bindings) > 32 {
		return Artifact{}, ErrInvalid
	}
	inventory := make([]dhcpserver.Binding, len(bindings))
	byID := make(map[string]Binding, len(bindings))
	names := map[string]bool{}
	subnetIDs := map[uint32]bool{}
	for i, b := range bindings {
		if !interfaceName(b.Name) || b.Interface.Role != "lan" || !b.Interface.Address.IsValid() || !b.Interface.Address.Addr().Is4() || b.SubnetID == 0 || b.SubnetID == ^uint32(0) || names[b.Name] || subnetIDs[b.SubnetID] {
			return Artifact{}, ErrInvalid
		}
		if _, exists := byID[b.Interface.InterfaceID]; exists {
			return Artifact{}, ErrInvalid
		}
		inventory[i] = b.Interface
		byID[b.Interface.InterfaceID] = b
		names[b.Name] = true
		subnetIDs[b.SubnetID] = true
	}
	if config.Validate(inventory) != nil {
		return Artifact{}, ErrInvalid
	}
	raw, err := json.Marshal(config)
	if err != nil || len(raw) > dhcpserver.MaxConfigBytes {
		return Artifact{}, ErrInvalid
	}
	if !config.Enabled {
		return Artifact{}, nil
	}

	service := server{
		Interfaces:      interfaces{Names: make([]string, 0, len(bindings)), SocketType: "raw", RequireAll: true, MaxRetries: 0},
		Database:        database{Type: "memfile", Persist: true, Name: LeaseFile, LFCInterval: 3600, MaxRowErrors: 1},
		HostIdentifiers: []string{"hw-address"}, MatchClientID: true,
		ReservationsInSubnet: true, ReservationsOutOfPool: true,
		Classes:              []clientClass{{Name: "DROP", Test: "not (pkt4.giaddr == 0.0.0.0) or option[82].exists"}},
		Sanity:               sanity{LeaseChecks: "warn"},
		Subnets:              make([]subnet, 0, len(config.Scopes)),
		Loggers:              []logger{{Name: "kea-dhcp4", Severity: "WARN", Outputs: []logOutput{{Output: "stdout"}}}},
		StatisticSampleCount: 1,
	}
	for _, b := range bindings {
		service.Interfaces.Names = append(service.Interfaces.Names, b.Name)
	}
	sort.Strings(service.Interfaces.Names)
	scopes := append([]dhcpserver.Scope(nil), config.Scopes...)
	sort.Slice(scopes, func(i, j int) bool { return scopes[i].ID < scopes[j].ID })
	for _, scope := range scopes {
		b := byID[scope.InterfaceID]
		// Kea can select by ciaddr/option-select before its interface fallback.
		// A subnet class constrains those paths to the same trusted ingress LAN.
		className := "andeiva-subnet-" + strconv.FormatUint(uint64(b.SubnetID), 10)
		service.Classes = append(service.Classes, clientClass{Name: className, Test: "pkt.iface == '" + b.Name + "'"})
		s := subnet{ID: b.SubnetID, Interface: b.Name, Subnet: scope.Subnet,
			ClientClass:   className,
			ValidLifetime: scope.LeaseSeconds, MinValidLifetime: scope.LeaseSeconds, MaxValidLifetime: scope.LeaseSeconds,
			Renew: scope.RenewSeconds, Rebind: scope.RebindSeconds,
			Pools: effectivePools(scope), Reservations: make([]reservation, 0, len(scope.Reservations)),
			Options: []option{{Name: "routers", Data: scope.Router}},
		}
		reservations := append([]dhcpserver.Reservation(nil), scope.Reservations...)
		sort.Slice(reservations, func(i, j int) bool { return reservations[i].MAC < reservations[j].MAC })
		for _, r := range reservations {
			s.Reservations = append(s.Reservations, reservation{MAC: r.MAC, Address: r.Address})
		}
		// DNS and NTP preference order is meaningful; do not sort these lists.
		if len(scope.DNS) > 0 {
			s.Options = append(s.Options, option{Name: "domain-name-servers", Data: strings.Join(scope.DNS, ", ")})
		}
		if len(scope.NTP) > 0 {
			s.Options = append(s.Options, option{Name: "ntp-servers", Data: strings.Join(scope.NTP, ", ")})
		}
		if scope.Domain != "" {
			s.Options = append(s.Options, option{Name: "domain-name", Data: scope.Domain})
		}
		service.Subnets = append(service.Subnets, s)
	}
	raw, err = json.Marshal(document{DHCP4: service})
	if err != nil || len(raw)+1 > MaxArtifactBytes {
		return Artifact{}, ErrInvalid
	}
	raw = append(raw, '\n')
	sum := sha256.Sum256(raw)
	return Artifact{Enabled: true, JSON: raw, Digest: hex.EncodeToString(sum[:])}, nil
}

func interfaceName(name string) bool {
	if len(name) == 0 || len(name) > 15 || name == "lo" || name == "." || name == ".." {
		return false
	}
	for i, c := range name {
		if c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9' {
			continue
		}
		if i == 0 || c != '_' && c != '-' && c != '.' {
			return false
		}
	}
	return true
}

type span struct{ first, last uint64 }

func number(s string) uint64 {
	b := netip.MustParseAddr(s).As4()
	return uint64(b[0])<<24 | uint64(b[1])<<16 | uint64(b[2])<<8 | uint64(b[3])
}
func address(n uint64) string {
	return netip.AddrFrom4([4]byte{byte((n >> 24) & 0xff), byte((n >> 16) & 0xff), byte((n >> 8) & 0xff), byte(n & 0xff)}).String()
}

// Split intervals at excluded/reserved addresses without enumerating a subnet.
// Validation has already bounded all arrays and checked canonical IPv4 values.
func effectivePools(s dhcpserver.Scope) []pool {
	cut := make([]uint64, 0, len(s.Excluded)+len(s.Reservations))
	for _, a := range s.Excluded {
		cut = append(cut, number(a))
	}
	for _, r := range s.Reservations {
		cut = append(cut, number(r.Address))
	}
	sort.Slice(cut, func(i, j int) bool { return cut[i] < cut[j] })
	ranges := make([]span, 0, len(s.Pools))
	for _, p := range s.Pools {
		ranges = append(ranges, span{number(p.First), number(p.Last)})
	}
	sort.Slice(ranges, func(i, j int) bool { return ranges[i].first < ranges[j].first })
	out := make([]pool, 0, len(ranges)+len(cut))
	for _, p := range ranges {
		first := p.first
		for _, n := range cut {
			if n < first {
				continue
			}
			if n > p.last {
				break
			}
			if n > first {
				out = append(out, pool{Range: address(first) + " - " + address(n-1)})
			}
			first = n + 1
		}
		if first <= p.last {
			out = append(out, pool{Range: address(first) + " - " + address(p.last)})
		}
	}
	return out
}
